// 1. Preprocessing parity
// ---------------------------------------------------------------------------

test('TS MFCC matches python_speech_features bit-for-bit', () => {
  const fixture = readFixture<{
    sampleRate: number;
    winlen: number;
    winstep: number;
    pcm: number[];
    mfcc: number[][];
  }>('mfcc-fixture.json');
  const result = computeMfcc(
    Int16Array.from(fixture.pcm),
    fixture.sampleRate,
    fixture.winlen,
    fixture.winstep,
  );
  assert.equal(result.frames, fixture.mfcc.length, 'frame count must match the library');
  let worst = 0;
  for (let frame = 0; frame < result.frames; frame += 1) {
    for (let k = 0; k < MFCC_COEFFS; k += 1) {
      worst = Math.max(worst, Math.abs(result.features[frame * MFCC_COEFFS + k] - fixture.mfcc[frame][k]));
    }
  }
  // The fixture stores 6 decimals, so this is "as equal as the file can express".
  assert.ok(worst < 1e-4, `worst MFCC difference ${worst}`);
});

test('four MFCC frames are grouped per 25 fps video frame, zero padded at the end', () => {
  const pcm = new Int16Array(1600); // 0.1 s of silence
  const { features, frames } = computeMfcc(pcm, 16000);
  assert.ok(frames >= 8);
  const block = mfccForVideoFrame(features, frames, 0);
  assert.equal(block.length, MFCC_COEFFS * 4);
  // Reading far past the end yields zeros instead of throwing (short audio).
  const beyond = mfccForVideoFrame(features, frames, 10_000);
  assert.ok(beyond.every((value) => value === 0));
});

test('the LR-ASD crop is the reference mouth-centred square', () => {
  const face = { cx: 500, cy: 400, w: 100, h: 120 };
  const box = lrAsdCropBox(face);
  // side = 0.7 * max(w, h) = 84, shifted down by 0.2 * 120 = 24.
  assert.equal(box.side, 84);
  assert.equal(box.x, 500 - 42);
  assert.equal(box.y, 400 - 42 + 24);
});

test('the LR-ASD crop is grayscale 112x112 and pads outside the frame with 110', () => {
  const width = 64;
  const height = 64;
  const data = new Uint8Array(width * height * 4);
  for (let i = 0; i < width * height; i += 1) {
    data[i * 4] = 200;
    data[i * 4 + 1] = 100;
    data[i * 4 + 2] = 50;
    data[i * 4 + 3] = 255;
  }
  const inside = cropFaceGray({ data, width, height }, { cx: 32, cy: 32, w: 40, h: 40 });
  assert.equal(inside.length, LR_ASD_CROP_SIZE * LR_ASD_CROP_SIZE);
  // 0.299*200 + 0.587*100 + 0.114*50 = 124.15 (gray, never the RGB channels).
  assert.ok(Math.abs(inside[0] - 124.15) < 0.5, `first pixel ${inside[0]}`);

  // A face at the frame edge: the outside part is the reference's pad value 110.
  const edge = cropFaceGray({ data, width, height }, { cx: 0, cy: 0, w: 40, h: 40 });
  assert.ok(edge.some((value) => Math.abs(value - 110) < 1e-6));
});

