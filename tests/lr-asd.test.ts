const FIXTURES = path.join(process.cwd(), 'tests', 'fixtures');
const FPS = 4;

function readFixture<T>(name: string): T {
  return JSON.parse(fs.readFileSync(path.join(FIXTURES, name), 'utf8')) as T;
}

