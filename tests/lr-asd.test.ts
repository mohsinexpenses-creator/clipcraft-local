// 2. ONNX <-> PyTorch parity
// ---------------------------------------------------------------------------

const modelsPresent = lrAsdModelPresent();

test(
  'ONNX output matches PyTorch on one short sample',
  { skip: modelsPresent ? false : 'models/lr-asd ONNX files not present (run npm run setup:asd)' },
  async () => {
    const fixture = readFixture<{
      frames: number;
      audio: string;
      video: string;
      scoresAV: number[];
      scoresV: number[];
      embedA: number[];
      embedV: number[];
    }>('lr-asd-parity.json');
    const { loadLrAsd } = await import('../worker/asd/lr-asd');
    const runtime = await loadLrAsd();
    assert.ok(runtime, 'expected the LR-ASD runtime to load');

    const ort = await import('onnxruntime-node' as never).then(
      (module) => (module as unknown as { default?: unknown }).default ?? module,
    ) as {
      Tensor: new (type: string, data: Float32Array, dims: number[]) => unknown;
    };
    const decode = (base64: string) => {
      const buffer = Buffer.from(base64, 'base64');
      return new Float32Array(buffer.buffer, buffer.byteOffset, buffer.byteLength / 4);
    };
    const audio = decode(fixture.audio);
    const video = decode(fixture.video);
    const frames = fixture.frames;

    const frontendOut = await runtime!.frontend.run({
      audio: new ort.Tensor('float32', Float32Array.from(audio), [1, frames * 4, 13]) as never,
      video: new ort.Tensor('float32', Float32Array.from(video), [1, frames, 112, 112]) as never,
    });
    const embedA = (frontendOut.embedA ?? Object.values(frontendOut)[0]).data as Float32Array;
    const embedV = (frontendOut.embedV ?? Object.values(frontendOut)[1]).data as Float32Array;

    const backendOut = await runtime!.backend.run({
      embedA: new ort.Tensor('float32', Float32Array.from(embedA), [1, frames, 128]) as never,
      embedV: new ort.Tensor('float32', Float32Array.from(embedV), [1, frames, 128]) as never,
    });
    const scoresAV = (backendOut.scoresAV ?? Object.values(backendOut)[0]).data as Float32Array;
    const scoresV = (backendOut.scoresV ?? Object.values(backendOut)[1]).data as Float32Array;

    for (let i = 0; i < frames; i += 1) {
      assert.ok(
        Math.abs(scoresAV[i] - fixture.scoresAV[i]) < 1e-3,
        `scoresAV[${i}] ONNX ${scoresAV[i]} vs torch ${fixture.scoresAV[i]}`,
      );
      assert.ok(
        Math.abs(scoresV[i] - fixture.scoresV[i]) < 1e-3,
        `scoresV[${i}] ONNX ${scoresV[i]} vs torch ${fixture.scoresV[i]}`,
      );
    }
    // The embeddings are the frontend's contract; they must agree too.
    let worst = 0;
    for (let i = 0; i < embedA.length; i += 1) {
      worst = Math.max(worst, Math.abs(embedA[i] - fixture.embedA[i]));
      worst = Math.max(worst, Math.abs(embedV[i] - fixture.embedV[i]));
    }
    assert.ok(worst < 2e-3, `worst embedding difference ${worst}`);
  },
);

test('an equal-score pair maps to an undecided 50/50 likelihood', () => {
  assert.ok(Math.abs(lrAsdLikelihood(0) - 0.5) < 1e-9);
  assert.ok(lrAsdLikelihood(2) > 0.9);
  assert.ok(lrAsdLikelihood(-2) < 0.1);
  assert.equal(lrAsdLikelihood(Number.NaN), 0.5);
});

// ---------------------------------------------------------------------------
// 3. The fusion: ambiguous windows only, budgeted, and unchanged without it
// ---------------------------------------------------------------------------

const DURATION = 8;
const FRAME_WIDTH = 1920;

function makeTrack(
  id: number,
  cx: number,
  w: number,
  motion: (index: number) => number | null,
): Track {
  const points: TrackPoint[] = [];
  for (let index = 0; index < DURATION * FPS; index += 1) {
    points.push({
      t: index / FPS,
      cx,
      cy: 400,
      w,
      mouthOpen: null,
      motion: motion(index),
    });
  }
  return {
    id,
    points,
    visibleTime: DURATION,
    avgW: w,
    maxW: w,
    cx,
    cy: 400,
    vx: 0,
    vy: 0,
    lastT: DURATION,
    missed: 0,
  };
}

/** Two similar faces, identical motion and size: the cheap cues tie exactly. */
function tiedTracks(): Track[] {
  const motion = (index: number) => (index % 4 === 0 ? 0.05 : 0.01);
  return [makeTrack(1, 600, 120, motion), makeTrack(2, 1300, 120, motion)];
}

function voiceEnvelope(value: number): number[] {
  return new Array(DURATION * FPS).fill(value);
}

test('no model => the timeline is byte-identical to today\'s behaviour', async () => {
  const tracks = tiedTracks();
  const voice = voiceEnvelope(0.7);
  const withoutReferee = await buildSpeakerTimeline({
    duration: DURATION,
    fps: FPS,
    voice,
    tracks,
    frameWidth: FRAME_WIDTH,
  });
  // A referee that is present but cannot decide (model missing) behaves the same.
  const refused: SpeakerReferee = { judge: () => null };
  const withRefusal = await buildSpeakerTimeline({
    duration: DURATION,
    fps: FPS,
    voice,
    tracks,
    frameWidth: FRAME_WIDTH,
    referee: refused,
  });
  assert.deepEqual(withRefusal.segments, withoutReferee.segments);
  assert.equal(withRefusal.speakerCount, withoutReferee.speakerCount);
  assert.equal(withRefusal.ambiguousWindows.length, 0);
});

test('an ambiguous window is resolved by the audio-visual cue', async () => {
  const tracks = tiedTracks();
  const windows: AmbiguousWindow[] = [];
  const referee: SpeakerReferee = {
    weight: 0.35,
    judge: (window) => {
      windows.push(window);
      // The model decides person#2 is the one talking.
      return new Map([
        [window.trackIds[0], 0.02],
        [window.trackIds[1], 0.98],
      ]);
    },
  };
  const result = await buildSpeakerTimeline({
    duration: DURATION,
    fps: FPS,
    voice: voiceEnvelope(0.7),
    tracks,
    frameWidth: FRAME_WIDTH,
    referee,
  });
  assert.ok(windows.length > 0, 'the tie must be reported as ambiguous');
  assert.deepEqual(windows[0].trackIds.slice().sort(), [1, 2]);
  assert.equal(windows[0].reason, 'top-two-close');
  // The verdict wins ties: person#2 holds the label for most of the clip.
  const winnerTime = result.segments
    .filter((segment) => segment.trackId === 2)
    .reduce((sum, segment) => sum + (segment.t1 - segment.t0), 0);
  assert.ok(winnerTime > DURATION / 2, `person#2 held ${winnerTime}s of ${DURATION}s`);
  assert.ok(result.ambiguousWindows.length > 0);
});

test('the referee is never consulted about a confident window', async () => {
  // One face is large and moving with the audio, the other is small and still.
  const strong = makeTrack(1, 600, 320, (index) => (index % 3 === 0 ? 0.08 : 0.02));
  const weak = makeTrack(2, 1500, 110, () => 0.002);
  let asked = 0;
  const result = await buildSpeakerTimeline({
    duration: DURATION,
    fps: FPS,
    voice: voiceEnvelope(0.8),
    tracks: [strong, weak],
    frameWidth: FRAME_WIDTH,
    referee: {
      judge: () => {
        asked += 1;
        return new Map([
          [1, 0.9],
          [2, 0.1],
        ]);
      },
    },
  });
  assert.equal(asked, 0, 'a clear speaker must not cost an LR-ASD pass');
  assert.equal(result.ambiguousWindows.length, 0);
  assert.equal(result.segments.find((segment) => segment.trackId !== null)?.trackId, 1);
});

test('a single visible person never reaches the referee, and shots are respected', async () => {
  const solo = makeTrack(1, 700, 200, (index) => (index % 3 === 0 ? 0.06 : 0.02));
  let asked = 0;
  const result = await buildSpeakerTimeline({
    duration: DURATION,
    fps: FPS,
    voice: voiceEnvelope(0.7),
    tracks: [solo],
    frameWidth: FRAME_WIDTH,
    shotCuts: [4],
    referee: {
      judge: () => {
        asked += 1;
        return null;
      },
    },
  });
  assert.equal(asked, 0);
  // Shot-cut behaviour is untouched: runs never cross the cut.
  assert.ok(result.segments.every((segment) => segment.t0 >= 4 || segment.t1 <= 4 + 1e-6));
});

test('a broken referee cannot break the timeline', async () => {
  const result = await buildSpeakerTimeline({
    duration: DURATION,
    fps: FPS,
    voice: voiceEnvelope(0.7),
    tracks: tiedTracks(),
    frameWidth: FRAME_WIDTH,
    referee: {
      judge: () => {
        throw new Error('model exploded');
      },
    },
  });
  assert.ok(result.segments.length > 0);
  assert.equal(result.ambiguousWindows.length, 0);
});

test('LR-ASD is on by default with a bounded budget, and can be switched off', () => {
  const settings = getLrAsdSettings({});
  assert.equal(settings.enabled, true);
  assert.ok(settings.maxWindows > 0 && settings.maxWindows <= 50);
  assert.ok(settings.maxFrames >= 16 && settings.maxFrames <= 200);
  assert.ok(settings.weight > 0 && settings.weight <= 0.5);
  assert.equal(getLrAsdSettings({ LR_ASD_ENABLED: '0' }).enabled, false);
  // A hostile value cannot turn it into an unbounded job.
  assert.equal(getLrAsdSettings({ LR_ASD_MAX_WINDOWS: '9999' }).maxWindows, 200);
  assert.equal(getLrAsdSettings({ LR_ASD_WEIGHT: '5' }).weight, 0.5);
});

// ---------------------------------------------------------------------------
// The worker's two-pass coordinator (exported for exactly this test)
// ---------------------------------------------------------------------------

test('the coordinator scores only ambiguous windows, within budget, and stops there', async () => {
  const { planLrAsdWindows } = await import('../worker/asd/index');
  const tracks = tiedTracks();
  const voice = voiceEnvelope(0.7);
  const input = {
    duration: DURATION,
    fps: FPS,
    voice,
    tracks,
    frameWidth: FRAME_WIDTH,
  };

  // 1) A tie: the cheap pass reports windows, the coordinator would score them.
  const tied = planLrAsdWindows(input, { maxWindows: 3 });
  assert.ok(tied.ambiguous.length > 0, 'a tie must be reported');
  assert.ok(tied.ambiguous.length <= DURATION / 0.25);
  // Identical windows are deduplicated: one span is scored at most once.
  const keys = tied.ambiguous.map((window) => `${window.t0}|${window.t1}`);
  assert.equal(new Set(keys).size, keys.length);

  // 2) A clear speaker: nothing to score, so the model is never loaded.
  const strong = makeTrack(1, 600, 320, (index) => (index % 3 === 0 ? 0.08 : 0.02));
  const weak = makeTrack(2, 1500, 110, () => 0.002);
  const clear = planLrAsdWindows(
    { ...input, tracks: [strong, weak], voice: voiceEnvelope(0.8) },
    { maxWindows: 3 },
  );
  assert.equal(clear.ambiguous.length, 0);

  // 3) The budget is clamped and reported (the judging loop stops at it).
  const capped = planLrAsdWindows(input, { maxWindows: 2 });
  assert.equal(capped.budget, 2);
  assert.equal(planLrAsdWindows(input, { maxWindows: 9_999 }).budget, 200);
  // 4) And the pass costs nothing: the returned timeline is the no-model one.
  assert.deepEqual(capped.timeline.segments, tied.timeline.segments);
});
