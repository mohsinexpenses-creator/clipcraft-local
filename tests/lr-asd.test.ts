/**
 * Change 3 - LR-ASD decides the ACTIVE SPEAKER when the cheap cues cannot.
 *
 * The existing fusion is excellent when one person clearly talks, and blind when
 * two similar faces both move with the audio (one nodding listener, a split
 * screen, two hosts with similar voices). LR-ASD looks at each face's mouth and
 * listens to the audio at the same time, which no single-frame cue can do - but it
 * is far too expensive to run everywhere, so it is only asked about AMBIGUOUS
 * windows, for at most two people, under a hard budget.
 *
 * What is covered here:
 *   1. preprocessing parity - the TS MFCC matches python_speech_features
 *      bit-for-bit (fixture generated by scripts/export-asd-onnx.py), and the
 *      face crop follows the reference's 0.7/0.2 mouth-centred geometry;
 *   2. ONNX <-> PyTorch parity on one short sample (the PyTorch scores are in the
 *      fixture, so this runs without torch);
 *   3. the fusion behaviour: an ambiguous window is resolved by the new cue, a
 *      confident window is never sent to it, and with no model the timeline is
 *      exactly what it was before.
 */
