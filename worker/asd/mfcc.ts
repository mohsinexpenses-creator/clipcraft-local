/**
 * MFCC features for the LR-ASD active speaker model, matching
 * `python_speech_features.mfcc()` - the library the model was TRAINED on.
 *
 * Any drift here (framing, filterbank, DCT scaling, liftering) shifts the
 * features the network sees, so this is a line-by-line port of that library's
 * defaults rather than "a" mel-cepstrum implementation:
 *
 *   winlen 0.025 s, winstep 0.010 s, numcep 13, nfilt 26, nfft 512,
 *   pre-emph 0.97, `hamming` window, `logfbank` + orthonormal DCT-II,
 *   ceplifter 22, and c0 REPLACED by log(frame energy).
 *
 * The frame count is `1 + ceil((len - frameLen) / frameStep)` exactly as the
 * library computes it, which is why `tests/lr-asd.test.ts` also checks a
 * 1-second signal against a fixture generated by the real Python library.
 *
 * Pure maths: no I/O, no model - unit-testable anywhere.
 */

export const MFCC_COEFFS = 13;
const NFFT = 512;
const NFILT = 26;
const PREEMPH = 0.97;
const CEPLIFTER = 22;

function hzToMel(hz: number): number {
  return 2595 * Math.log10(1 + hz / 700);
}

function melToHz(mel: number): number {
  return 700 * (Math.pow(10, mel / 2595) - 1);
}

/** Triangular mel filterbank, NFILT x (NFFT/2 + 1), matching get_filterbanks. */
function buildFilterbank(sampleRate: number): Float64Array[] {
  const lowMel = hzToMel(0);
  const highMel = hzToMel(sampleRate / 2);
  const melPoints = Array.from(
    { length: NFILT + 2 },
    (_, i) => lowMel + ((highMel - lowMel) * i) / (NFILT + 1),
  );
  const bin = melPoints.map((mel) =>
    Math.floor(((NFFT + 1) * melToHz(mel)) / sampleRate),
  );
  const bank = Array.from({ length: NFILT }, () => new Float64Array(NFFT / 2 + 1));
  for (let j = 0; j < NFILT; j += 1) {
    const left = bin[j];
    const middle = bin[j + 1];
    const right = bin[j + 2];
    for (let i = left; i < middle; i += 1) {
      bank[j][i] = (i - left) / (middle - left);
    }
    for (let i = middle; i < right; i += 1) {
      bank[j][i] = (right - i) / (right - middle);
    }
  }
  return bank;
}

/** DCT-II with orthonormal scaling, first MFCC_COEFFS rows. */
function buildDctMatrix(): Float64Array[] {
  const rows: Float64Array[] = [];
  for (let k = 0; k < MFCC_COEFFS; k += 1) {
    const row = new Float64Array(NFILT);
    const scale = k === 0 ? Math.sqrt(1 / (4 * NFILT)) : Math.sqrt(1 / (2 * NFILT));
    for (let n = 0; n < NFILT; n += 1) {
      row[n] = 2 * scale * Math.cos((Math.PI * k * (2 * n + 1)) / (2 * NFILT));
    }
    rows.push(row);
  }
  return rows;
}

/** In-place iterative radix-2 FFT over interleaved [re, im] pairs. */
function fft(buf: Float64Array): void {
  const n = buf.length / 2;
  for (let i = 1, j = 0; i < n; i += 1) {
    let bit = n >> 1;
    for (; j & bit; bit >>= 1) j ^= bit;
    j ^= bit;
    if (i < j) {
      const ti = buf[2 * i];
      const tq = buf[2 * i + 1];
      buf[2 * i] = buf[2 * j];
      buf[2 * i + 1] = buf[2 * j + 1];
      buf[2 * j] = ti;
      buf[2 * j + 1] = tq;
    }
  }
  for (let len = 2; len <= n; len <<= 1) {
    const ang = (-2 * Math.PI) / len;
    const wRe = Math.cos(ang);
    const wIm = Math.sin(ang);
    for (let i = 0; i < n; i += len) {
      let curRe = 1;
      let curIm = 0;
      for (let k = 0; k < len / 2; k += 1) {
        const a = 2 * (i + k);
        const b = 2 * (i + k + len / 2);
        const bRe = buf[b] * curRe - buf[b + 1] * curIm;
        const bIm = buf[b] * curIm + buf[b + 1] * curRe;
        buf[b] = buf[a] - bRe;
        buf[b + 1] = buf[a + 1] - bIm;
        buf[a] += bRe;
        buf[a + 1] += bIm;
        const nextRe = curRe * wRe - curIm * wIm;
        curIm = curRe * wIm + curIm * wRe;
        curRe = nextRe;
      }
    }
  }
}

/**
 * `python_speech_features.mfcc()` calls `fbank()` with its DEFAULT winfunc,
 * which is a rectangular window (all ones). The model was trained on those
 * features, so no Hamming/Hann taper is applied here either.
 */

export interface MfccResult {
  /** Row-major [frames x MFCC_COEFFS]. */
  features: Float32Array;
  frames: number;
}

/**
 * MFCC features from 16-bit mono PCM.
 *
 * `winlen`/`winstep` are seconds. The ASC pipeline uses the reference values
 * (0.025 / 0.010) so that four MFCC frames line up with every 25 fps video
 * frame - exactly how LR-ASD's own dataloader aligns audio and video.
 */
export function computeMfcc(
  pcm: Int16Array,
  sampleRate: number,
  winlen = 0.025,
  winstep = 0.01,
): MfccResult {
  const frameLen = Math.round(winlen * sampleRate);
  const frameStep = Math.round(winstep * sampleRate);

  // Pre-emphasis (signal[0] = pcm[0], as in python_speech_features).
  const signal = new Float64Array(pcm.length);
  if (pcm.length > 0) signal[0] = pcm[0];
  for (let i = 1; i < pcm.length; i += 1) {
    signal[i] = pcm[i] - PREEMPH * pcm[i - 1];
  }

  const slen = signal.length;
  const frames =
    slen <= frameLen ? 1 : 1 + Math.ceil((slen - frameLen) / frameStep);

  const filterbank = buildFilterbank(sampleRate);
  const dct = buildDctMatrix();
  const lifter = Array.from(
    { length: MFCC_COEFFS },
    (_, i) => 1 + (CEPLIFTER / 2) * Math.sin((Math.PI * i) / CEPLIFTER),
  );
  const eps = Number.EPSILON;

  const features = new Float32Array(frames * MFCC_COEFFS);
  const fftBuf = new Float64Array(NFFT * 2);
  const pspec = new Float64Array(NFFT / 2 + 1);
  const fbankLog = new Float64Array(NFILT);

  for (let f = 0; f < frames; f += 1) {
    const start = f * frameStep;
    const copyLen = Math.min(frameLen, Math.max(0, slen - start));
    fftBuf.fill(0);
    // Windowed samples, then a power spectrum normalised by NFFT (the library's
    // `abs(fft(frame)) ** 2 / NFFT`, one-sided).
    for (let i = 0; i < copyLen; i += 1) {
      // Rectangular window (the library default): the frame is copied as-is and
      // zero padded up to NFFT.
      fftBuf[2 * i] = signal[start + i];
    }

    fft(fftBuf);

    let energy = 0;
    for (let i = 0; i <= NFFT / 2; i += 1) {
      const re = fftBuf[2 * i];
      const im = fftBuf[2 * i + 1];
      pspec[i] = (re * re + im * im) / NFFT;
      energy += pspec[i];
    }
    if (energy === 0) energy = eps;

    for (let j = 0; j < NFILT; j += 1) {
      const fb = filterbank[j];
      let sum = 0;
      for (let i = 0; i <= NFFT / 2; i += 1) sum += pspec[i] * fb[i];
      fbankLog[j] = Math.log(sum === 0 ? eps : sum);
    }

    for (let k = 0; k < MFCC_COEFFS; k += 1) {
      const row = dct[k];
      let sum = 0;
      for (let n = 0; n < NFILT; n += 1) sum += fbankLog[n] * row[n];
      features[f * MFCC_COEFFS + k] = sum * lifter[k];
    }
    // c0 is the log frame energy in this library's `logfbank` path.
    features[f * MFCC_COEFFS] = Math.log(energy);
  }

  return { features, frames };
}

/**
 * The 4 MFCC frames belonging to video frame `index` (25 fps video, 100 fps
 * MFCC), or a zero vector when the audio is shorter than the video.
 */
export function mfccForVideoFrame(
  features: Float32Array,
  frames: number,
  index: number,
): Float32Array {
  const out = new Float32Array(MFCC_COEFFS * 4);
  for (let sub = 0; sub < 4; sub += 1) {
    const source = index * 4 + sub;
    if (source >= frames) continue;
    for (let k = 0; k < MFCC_COEFFS; k += 1) {
      out[sub * MFCC_COEFFS + k] = features[source * MFCC_COEFFS + k];
    }
  }
  return out;
}
